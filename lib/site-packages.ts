export type SitePlan = "free" | (typeof SITE_PACKAGES)[number]["id"];

export function getSitePackage(plan: SitePlan) {
  return SITE_PACKAGES.find((sitePackage) => sitePackage.id === plan) ?? null;
}

/** Clave del campo de texto de un paquete: `sitePackageKey("super", "price")`. */
export function sitePackageKey(plan: SitePlan, field: "name" | "price" | "capacity" | "idealFor") {
  return `es.packages.${plan}.${field}`;
}
